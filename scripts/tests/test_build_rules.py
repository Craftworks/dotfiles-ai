# Test specification for build-rules.
#
# Mapping to the done conditions in scripts/SPEC.md:
#   Condition 1 (match the real files)       -> RealRulesSnapshotTest
#   Condition 2 (idempotent)                 -> IdempotencyTest
#   Condition 3 (--check)                    -> CheckModeTest
#   Condition 4 (write nothing on bad input) -> InvalidInputTest
#   Condition 5 (globs -> paths)             -> GoldenFixtureTest.test_globs
#
# Format fixed here (the tests decide this as the specification):
#   - Cursor frontmatter is ordered description, globs, alwaysApply.
#     Values are unquoted plain scalars, matching the current .mdc files.
#   - No generated-file header. That a file was generated is guaranteed
#     by --check and by this specification, not by text inside the file,
#     so the tokens and the top of the file stay available for the body.
#   - A validation error is written to stderr and includes the rule name,
#     the cause string in CAUSES for that case, and the next-action string
#     in ACTIONS for that case.
#   - --check names every drifted or missing deliverable. A name ending in
#     .md does not count as the .mdc file. --check writes nothing.

import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from support import install_scripts

TESTS_DIR = Path(__file__).resolve().parent
FIXTURES = TESTS_DIR / "fixtures"


def run_build(root: Path, *extra: str) -> subprocess.CompletedProcess:
    """Run build-rules. The fixtures are Japanese editions, so --lang ja is
    passed unless the test passes its own --lang."""
    lang = [] if "--lang" in extra else ["--lang", "ja"]
    return subprocess.run(
        [sys.executable, str(install_scripts(root) / "build-rules"), *lang, *extra],
        capture_output=True, text=True,
        env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"),
    )


def make_root(fixture: Path) -> Path:
    tmp = Path(tempfile.mkdtemp(prefix="build-rules-test-")).resolve()
    shutil.copytree(fixture / "rules.ja", tmp / "rules.ja")
    install_scripts(tmp)
    return tmp


def read_tree(root: Path) -> dict:
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file():
            out[p.relative_to(root).as_posix()] = p.read_bytes()
    return out


def generated_outputs(root: Path) -> dict:
    return {k: v for k, v in read_tree(root).items()
            if k.startswith(".cursor/") or k.startswith(".claude/")}


def deliverable_paths(names: set[str]) -> list[str]:
    """Order build-rules prints: rule name, then Cursor, then Claude."""
    rules = sorted({Path(name).stem for name in names})
    paths = []
    for rule in rules:
        paths.append(f".cursor/rules/{rule}.mdc")
        paths.append(f".claude/rules/{rule}.md")
    return paths


def success_report(root: Path, paths: list[str], *, check: bool) -> str:
    count = len(paths)
    if check:
        summary = (
            f"checked {count} files from rules.ja under {root}; "
            "all match; wrote nothing"
        )
    else:
        summary = f"wrote {count} files from rules.ja under {root}"
    return summary + "\n" + "".join(f"{path}\n" for path in paths)


def assert_names_file(testcase: unittest.TestCase, text: str, filename: str):
    """filename must appear, and sample.md must not match sample.mdc."""
    testcase.assertRegex(text, re.escape(filename) + r"(?![\w])")


# Cause text that stderr must contain. The rule name alone is not enough.
CAUSES = {
    "missing-meta": "missing meta.json",
    "bad-json": "invalid JSON in meta.json",
    "unknown-key": 'unknown key "bogus"',
    "missing-body": "missing body.md",
    "mixed-valid": "missing body.md",
    "meta-not-object": "meta.json is not an object",
    "description-missing": "missing description",
    "description-not-string": "description is not a string",
    "cursor-missing": "missing cursor",
    "cursor-not-object": "cursor is not an object",
    "cursor-unknown-key": 'unknown key "bogus" in cursor',
    "globs-not-string": "globs is not a string",
    "always-apply-not-bool": "alwaysApply is not a boolean",
}

# Next action that stderr must contain, one sentence per case.
ACTIONS = {
    "missing-meta": "create meta.json",
    "bad-json": "fix meta.json",
    "unknown-key": "remove the unknown key or extend the schema",
    "missing-body": "create body.md",
    "mixed-valid": "create body.md",
    "meta-not-object": "replace meta.json with an object",
    "description-missing": "add a string description",
    "description-not-string": "set description to a string",
    "cursor-missing": "add a cursor object",
    "cursor-not-object": "set cursor to an object",
    "cursor-unknown-key": "remove the unknown key or extend the schema",
    "globs-not-string": "set globs to a string or null",
    "always-apply-not-bool": "set alwaysApply to true or false",
}


class GoldenFixtureTest(unittest.TestCase):
    """Expected files are generated byte for byte from the fixture input."""

    def check_case(self, case: str):
        fixture = FIXTURES / case
        root = make_root(fixture)
        result = run_build(root)
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        expected = read_tree(fixture / "expected")
        self.assertEqual(
            result.stdout,
            success_report(root, deliverable_paths(set(expected)), check=False),
        )
        self.assertEqual(result.stderr, "")
        actual = generated_outputs(root)
        self.assertEqual(set(actual), set(expected),
                         msg=f"generated file set differs: {sorted(actual)} vs {sorted(expected)}")
        for name, want in expected.items():
            self.assertEqual(actual[name], want, msg=f"{case}: contents of {name} differ from expected")

    def test_always(self):
        self.check_case("always")

    def test_globs(self):
        # Done condition 5: globs becomes paths in the Claude format (in the golden).
        self.check_case("globs")

    def test_auto(self):
        self.check_case("auto")


class IdempotencyTest(unittest.TestCase):
    def test_second_run_changes_nothing(self):
        root = make_root(FIXTURES / "auto")
        self.assertEqual(run_build(root).returncode, 0)
        first = read_tree(root)
        self.assertEqual(run_build(root).returncode, 0)
        self.assertEqual(read_tree(root), first)


class CheckModeTest(unittest.TestCase):
    def test_check_passes_on_clean_tree_and_fails_after_tamper(self):
        root = make_root(FIXTURES / "auto")
        self.assertEqual(run_build(root).returncode, 0)
        before = read_tree(root)
        ok = run_build(root, "--check")
        self.assertEqual(ok.returncode, 0, msg=ok.stderr)
        self.assertEqual(
            ok.stdout,
            success_report(root, deliverable_paths(set(generated_outputs(root))), check=True),
        )
        self.assertEqual(ok.stderr, "")
        self.assertEqual(read_tree(root), before, msg="--check rewrote files")

        target = root / ".cursor" / "rules" / "sample-auto.mdc"
        target.write_bytes(target.read_bytes() + b"tampered\n")
        tampered = read_tree(root)
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        report = ng.stdout + ng.stderr
        assert_names_file(self, report, "sample-auto.mdc")
        self.assertIn("differs: .cursor/rules/sample-auto.mdc", report)
        self.assertIn("deliverables do not match rules.ja", report)
        self.assertIn("run without --check to write them.", report)
        self.assertEqual(read_tree(root), tampered, msg="--check wrote files after a drift")

    def test_check_fails_when_outputs_missing(self):
        root = make_root(FIXTURES / "auto")
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        report = ng.stdout + ng.stderr
        self.assertIn("output directory does not exist", report)
        self.assertIn("missing: .cursor/rules", report)
        self.assertIn("missing: .claude/rules", report)
        self.assertNotIn("sample-auto.mdc", report)
        self.assertNotIn("sample-auto.md", report)
        self.assertIn("run without --check to write them.", report)
        self.assertFalse((root / ".cursor").exists(), msg="--check created .cursor")
        self.assertFalse((root / ".claude").exists(), msg="--check created .claude")

    def test_check_names_a_missing_rules_ja_when_outputs_are_missing(self):
        root = Path(tempfile.mkdtemp(prefix="build-rules-test-"))
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        self.assertEqual(ng.stdout, "")
        self.assertEqual(ng.stderr, "rules.ja: missing rules.ja. create rules.ja\n")
        self.assertFalse((root / ".cursor").exists())
        self.assertFalse((root / ".claude").exists())

    def test_check_names_an_invalid_rule_when_outputs_are_missing(self):
        root = make_root(FIXTURES / "invalid" / "missing-body")
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        self.assertEqual(ng.stdout, "")
        self.assertEqual(ng.stderr, "sample-x: missing body.md. create body.md\n")
        self.assertFalse((root / ".cursor").exists())
        self.assertFalse((root / ".claude").exists())

    def test_check_fails_when_output_directories_are_empty(self):
        root = make_root(FIXTURES / "auto")
        (root / ".cursor" / "rules").mkdir(parents=True)
        (root / ".claude" / "rules").mkdir(parents=True)
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        report = ng.stdout + ng.stderr
        self.assertIn("output directory is empty", report)
        self.assertIn("empty: .cursor/rules", report)
        self.assertIn("empty: .claude/rules", report)
        self.assertNotIn("sample-auto.mdc", report)
        self.assertNotIn("sample-auto.md", report)
        self.assertIn("run without --check to write them.", report)
        self.assertEqual(list((root / ".cursor" / "rules").iterdir()), [])
        self.assertEqual(list((root / ".claude" / "rules").iterdir()), [])

    def test_check_names_a_missing_file_when_a_sibling_remains(self):
        root = make_root(FIXTURES / "auto")
        shutil.copytree(
            root / "rules.ja" / "sample-auto",
            root / "rules.ja" / "sample-other",
        )
        self.assertEqual(run_build(root).returncode, 0)
        (root / ".cursor" / "rules" / "sample-auto.mdc").unlink()
        before = read_tree(root)
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        self.assertEqual(ng.stdout, "")
        self.assertEqual(
            ng.stderr,
            "deliverables do not match rules.ja. --check writes nothing.\n"
            "missing: .cursor/rules/sample-auto.mdc\n"
            "run without --check to write them.\n",
        )
        self.assertEqual(read_tree(root), before, msg="--check wrote files")

    def test_check_names_missing_files_when_unrelated_files_remain(self):
        root = make_root(FIXTURES / "auto")
        for rel in (".cursor/rules", ".claude/rules"):
            directory = root / rel
            directory.mkdir(parents=True)
            (directory / "notes.txt").write_text("x\n", encoding="utf-8")
        before = read_tree(root)
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        self.assertEqual(ng.stdout, "")
        self.assertEqual(
            ng.stderr,
            "deliverables do not match rules.ja. --check writes nothing.\n"
            "missing: .cursor/rules/sample-auto.mdc\n"
            "missing: .claude/rules/sample-auto.md\n"
            "run without --check to write them.\n",
        )
        self.assertEqual(read_tree(root), before, msg="--check changed unrelated files")


class InvalidInputTest(unittest.TestCase):
    """Done condition 4: invalid input exits with an error and writes no output."""

    def check_invalid(self, case: str):
        root = make_root(FIXTURES / "invalid" / case)
        result = run_build(root)
        self.assertNotEqual(result.returncode, 0, msg=f"{case}: did not exit with an error")
        assert_names_file(self, result.stderr, "sample-x")
        self.assertIn(CAUSES[case], result.stderr, msg=f"{case}: stderr does not state the cause")
        self.assertIn(ACTIONS[case], result.stderr,
                      msg=f"{case}: stderr does not state the next action")
        self.assertNotIn("Traceback", result.stderr, msg=f"{case}: stderr is a traceback")
        self.assertFalse((root / ".cursor").exists(), msg=f"{case}: .cursor was created")
        self.assertFalse((root / ".claude").exists(), msg=f"{case}: .claude was created")

    def test_missing_meta(self):
        self.check_invalid("missing-meta")

    def test_bad_json(self):
        self.check_invalid("bad-json")

    def test_unknown_key(self):
        self.check_invalid("unknown-key")

    def test_missing_body(self):
        self.check_invalid("missing-body")

    def test_valid_sibling_still_writes_nothing(self):
        # One valid rule beside one invalid rule must not be written either.
        self.check_invalid("mixed-valid")

    def test_meta_not_object(self):
        self.check_invalid("meta-not-object")

    def test_description_missing(self):
        self.check_invalid("description-missing")

    def test_description_not_string(self):
        self.check_invalid("description-not-string")

    def test_cursor_missing(self):
        self.check_invalid("cursor-missing")

    def test_cursor_not_object(self):
        self.check_invalid("cursor-not-object")

    def test_cursor_unknown_key(self):
        self.check_invalid("cursor-unknown-key")

    def test_globs_not_string(self):
        # null means absent. Every canonical meta.json uses "globs": null.
        self.check_invalid("globs-not-string")

    def test_always_apply_not_bool(self):
        self.check_invalid("always-apply-not-bool")

    def test_missing_rules_dir(self):
        self.assertFalse((FIXTURES / "invalid" / "missing-rules-ja" / "rules.ja").exists())
        root = Path(tempfile.mkdtemp(prefix="build-rules-test-"))
        result = run_build(root)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(result.stdout, "")
        self.assertEqual(result.stderr, "rules.ja: missing rules.ja. create rules.ja\n")
        self.assertNotIn("Traceback", result.stderr)
        self.assertFalse((root / ".cursor").exists())
        self.assertFalse((root / ".claude").exists())


def make_edition(lang: str) -> Path:
    """A repository whose only edition is rules.<lang>: the always fixture."""
    tmp = Path(tempfile.mkdtemp(prefix="build-rules-test-")).resolve()
    shutil.copytree(FIXTURES / "always" / "rules.ja", tmp / f"rules.{lang}")
    install_scripts(tmp)
    return tmp


class LangTest(unittest.TestCase):
    """--lang picks the edition rules.<lang>; the default is en."""

    def test_default_builds_from_the_english_edition(self):
        root = make_edition("en")
        result = subprocess.run(
            [sys.executable, str(root / "scripts" / "build-rules")],
            capture_output=True, text=True,
        )
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        self.assertTrue(result.stdout.startswith(f"wrote 2 files from rules.en under {root}\n"))
        self.assertTrue((root / ".cursor" / "rules" / "sample-always.mdc").is_file())

    def test_default_does_not_read_the_japanese_edition(self):
        root = make_edition("ja")
        result = subprocess.run(
            [sys.executable, str(root / "scripts" / "build-rules")],
            capture_output=True, text=True,
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(result.stderr, "rules.en: missing rules.en. create rules.en\n")
        self.assertFalse((root / ".cursor").exists())

    def test_an_explicit_language_selects_that_edition(self):
        root = make_edition("fr")
        result = run_build(root, "--lang", "fr")
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        self.assertTrue(result.stdout.startswith(f"wrote 2 files from rules.fr under {root}\n"))

    def test_check_reports_the_selected_edition(self):
        root = make_edition("fr")
        self.assertEqual(run_build(root, "--lang", "fr").returncode, 0)
        (root / ".claude" / "rules" / "sample-always.md").write_text("edited\n")
        result = run_build(root, "--lang", "fr", "--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("deliverables do not match rules.fr. --check writes nothing.", result.stderr)

    def test_a_repeated_lang_changes_nothing(self):
        root = make_edition("en")
        result = run_build(root, "--lang", "en", "--lang", "ja")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, "")
        self.assertEqual(
            result.stderr, "lang: --lang was given more than once. pass it once\n")
        self.assertFalse((root / ".cursor").exists())
        self.assertFalse((root / ".claude").exists())

    def test_a_value_that_is_not_a_language_code_changes_nothing(self):
        root = make_edition("en")
        result = run_build(root, "--lang", "../x")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(
            result.stderr,
            'lang: "../x" is not a language code. '
            "pass --lang with letters, digits, - or _, such as en or ja\n",
        )
        self.assertFalse((root / ".cursor").exists())


class RealRulesSnapshotTest(unittest.TestCase):
    """Done condition 1: the real 11 rules produce output that matches the
    frozen snapshot byte for byte.

    The snapshot is frozen under fixtures/real/. Both the input (a copy of
    rules.ja) and the expected output (finished .mdc / .md files) were taken
    on 2026-11-21, when build-rules was not yet implemented and .cursor/rules
    was still the hand-written original. The test does not read the
    repository's .cursor/rules: those files are themselves generated, and
    comparing generated files with generated files would make the test
    circular."""

    def test_real_rules_snapshot(self):
        fixture = FIXTURES / "real"
        root = make_root(fixture)
        result = run_build(root)
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        expected = read_tree(fixture / "expected")
        self.assertEqual(len(expected), 22)
        self.assertEqual(
            result.stdout,
            success_report(root, deliverable_paths(set(expected)), check=False),
        )
        self.assertEqual(result.stderr, "")
        actual = generated_outputs(root)
        self.assertEqual(set(actual), set(expected),
                         msg=f"generated file set differs: {sorted(actual)} vs {sorted(expected)}")
        for name, want in expected.items():
            self.assertEqual(actual[name], want, msg=f"real: contents of {name} differ from the snapshot")


