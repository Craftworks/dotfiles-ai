# Test specification for build-rules.
#
# Mapping to the done conditions in scripts/README:
#   Condition 1 (match the real files)       -> RealRulesSnapshotTest
#   Condition 2 (idempotent)                 -> IdempotencyTest
#   Condition 3 (--check)                    -> CheckModeTest
#   Condition 4 (write nothing on bad input) -> InvalidInputTest
#   Condition 5 (globs -> paths)             -> GoldenFixtureTest.test_globs
#
# Format fixed here (the tests decide this as the specification):
#   - Cursor frontmatter is ordered description, globs, alwaysApply.
#     Values are unquoted plain scalars, matching the current .mdc files.
#   - No generated-file header. That a file was generated is guaranteed
#     by --check and by this specification, not by text inside the file,
#     so the tokens and the top of the file stay available for the body.
#   - A validation error is written to stderr and includes the rule name,
#     the cause string in CAUSES for that case, and the next-action string
#     in ACTIONS for that case.
#   - --check names every drifted or missing deliverable. A name ending in
#     .md does not count as the .mdc file. --check writes nothing.

import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

TESTS_DIR = Path(__file__).resolve().parent
REPO_ROOT = TESTS_DIR.parents[1]
SCRIPT = REPO_ROOT / "scripts" / "build-rules"
FIXTURES = TESTS_DIR / "fixtures"


def run_build(root: Path, *extra: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--root", str(root), *extra],
        capture_output=True, text=True,
    )


def make_root(fixture: Path) -> Path:
    tmp = Path(tempfile.mkdtemp(prefix="build-rules-test-"))
    shutil.copytree(fixture / "rules.ja", tmp / "rules.ja")
    return tmp


def read_tree(root: Path) -> dict:
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file():
            out[p.relative_to(root).as_posix()] = p.read_bytes()
    return out


def generated_outputs(root: Path) -> dict:
    return {k: v for k, v in read_tree(root).items()
            if k.startswith(".cursor/") or k.startswith(".claude/")}


def assert_names_file(testcase: unittest.TestCase, text: str, filename: str):
    """filename must appear, and sample.md must not match sample.mdc."""
    testcase.assertRegex(text, re.escape(filename) + r"(?![\w])")


# Cause text that stderr must contain. The rule name alone is not enough.
CAUSES = {
    "missing-meta": "missing meta.json",
    "bad-json": "invalid JSON in meta.json",
    "unknown-key": 'unknown key "bogus"',
    "missing-body": "missing body.md",
    "mixed-valid": "missing body.md",
}

# Next action that stderr must contain, one sentence per case.
ACTIONS = {
    "missing-meta": "create meta.json",
    "bad-json": "fix meta.json",
    "unknown-key": "remove the unknown key or extend the schema",
    "missing-body": "create body.md",
    "mixed-valid": "create body.md",
}


class GoldenFixtureTest(unittest.TestCase):
    """Expected files are generated byte for byte from the fixture input."""

    def check_case(self, case: str):
        fixture = FIXTURES / case
        root = make_root(fixture)
        result = run_build(root)
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        expected = read_tree(fixture / "expected")
        actual = generated_outputs(root)
        self.assertEqual(set(actual), set(expected),
                         msg=f"generated file set differs: {sorted(actual)} vs {sorted(expected)}")
        for name, want in expected.items():
            self.assertEqual(actual[name], want, msg=f"{case}: contents of {name} differ from expected")

    def test_always(self):
        self.check_case("always")

    def test_globs(self):
        # Done condition 5: globs becomes paths in the Claude format (in the golden).
        self.check_case("globs")

    def test_auto(self):
        self.check_case("auto")


class IdempotencyTest(unittest.TestCase):
    def test_second_run_changes_nothing(self):
        root = make_root(FIXTURES / "auto")
        self.assertEqual(run_build(root).returncode, 0)
        first = read_tree(root)
        self.assertEqual(run_build(root).returncode, 0)
        self.assertEqual(read_tree(root), first)


class CheckModeTest(unittest.TestCase):
    def test_check_passes_on_clean_tree_and_fails_after_tamper(self):
        root = make_root(FIXTURES / "auto")
        self.assertEqual(run_build(root).returncode, 0)
        before = read_tree(root)
        ok = run_build(root, "--check")
        self.assertEqual(ok.returncode, 0, msg=ok.stderr)
        self.assertEqual(read_tree(root), before, msg="--check rewrote files")

        target = root / ".cursor" / "rules" / "sample-auto.mdc"
        target.write_bytes(target.read_bytes() + b"tampered\n")
        tampered = read_tree(root)
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        assert_names_file(self, ng.stdout + ng.stderr, "sample-auto.mdc")
        self.assertEqual(read_tree(root), tampered, msg="--check wrote files after a drift")

    def test_check_fails_when_outputs_missing(self):
        root = make_root(FIXTURES / "auto")
        ng = run_build(root, "--check")
        self.assertNotEqual(ng.returncode, 0)
        report = ng.stdout + ng.stderr
        assert_names_file(self, report, "sample-auto.mdc")
        assert_names_file(self, report, "sample-auto.md")
        self.assertFalse((root / ".cursor").exists(), msg="--check created .cursor")
        self.assertFalse((root / ".claude").exists(), msg="--check created .claude")


class InvalidInputTest(unittest.TestCase):
    """Done condition 4: invalid input exits with an error and writes no output."""

    def check_invalid(self, case: str):
        root = make_root(FIXTURES / "invalid" / case)
        result = run_build(root)
        self.assertNotEqual(result.returncode, 0, msg=f"{case}: did not exit with an error")
        assert_names_file(self, result.stderr, "sample-x")
        self.assertIn(CAUSES[case], result.stderr, msg=f"{case}: stderr does not state the cause")
        self.assertIn(ACTIONS[case], result.stderr,
                      msg=f"{case}: stderr does not state the next action")
        self.assertFalse((root / ".cursor").exists(), msg=f"{case}: .cursor was created")
        self.assertFalse((root / ".claude").exists(), msg=f"{case}: .claude was created")

    def test_missing_meta(self):
        self.check_invalid("missing-meta")

    def test_bad_json(self):
        self.check_invalid("bad-json")

    def test_unknown_key(self):
        self.check_invalid("unknown-key")

    def test_missing_body(self):
        self.check_invalid("missing-body")

    def test_valid_sibling_still_writes_nothing(self):
        # One valid rule beside one invalid rule must not be written either.
        self.check_invalid("mixed-valid")


class RealRulesSnapshotTest(unittest.TestCase):
    """Done condition 1: the real 11 rules produce output that matches the
    frozen snapshot byte for byte.

    The snapshot is frozen under fixtures/real/. Both the input (a copy of
    rules.ja) and the expected output (finished .mdc / .md files) were taken
    on 2026-11-21, when build-rules was not yet implemented and .cursor/rules
    was still the hand-written original. The test does not read the
    repository's .cursor/rules: those files are themselves generated, and
    comparing generated files with generated files would make the test
    circular."""

    def test_real_rules_snapshot(self):
        fixture = FIXTURES / "real"
        root = make_root(fixture)
        result = run_build(root)
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        expected = read_tree(fixture / "expected")
        self.assertEqual(len(expected), 22)
        actual = generated_outputs(root)
        self.assertEqual(set(actual), set(expected),
                         msg=f"generated file set differs: {sorted(actual)} vs {sorted(expected)}")
        for name, want in expected.items():
            self.assertEqual(actual[name], want, msg=f"real: contents of {name} differ from the snapshot")


if __name__ == "__main__":
    unittest.main()
